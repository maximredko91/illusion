package com.illusion.app.ui.player

import android.view.KeyEvent

/**
 * Мост между [com.illusion.app.MainActivity.dispatchKeyEvent] и экраном плеера.
 *
 * На Android TV панель управления плеером показывалась только по касанию экрана (onSingleTap), а
 * запасной путь для пульта - фокусируемый корневой узел с обработчиком DPAD_CENTER - работал лишь
 * пока фокус действительно оставался на нём. На реальном TV Box (проверено на Xiaomi MiTV-AFKR0,
 * Android 11, устройство без тачскрина) этого не происходило: нажатия пульта до плеера не доходили
 * вовсе, панель не появлялась, и управлять воспроизведением было нечем - только выход по «назад».
 *
 * Перехват на уровне активности не зависит ни от фокуса, ни от наличия тачскрина: пока экран плеера
 * на виду, он первым получает любое нажатие пульта.
 */
object PlayerKeyEvents {
    /** Возвращает true, если событие обработано плеером и дальше его передавать не нужно. */
    @Volatile
    var handler: ((KeyEvent) -> Boolean)? = null
}
