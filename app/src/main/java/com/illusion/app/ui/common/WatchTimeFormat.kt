package com.illusion.app.ui.common

/**
 * Сколько осталось смотреть - словами, а не таймкодом: «1 ч 4 мин» читается быстрее, чем второй
 * подряд часовой формат в одной строке. Общий для карточки фильма (подпись под кнопкой
 * «Продолжить») и для ряда «Продолжить просмотр» на главной, чтобы одно и то же число не
 * форматировалось в двух местах по-разному.
 *
 * Неразрывные пробелы между числом и единицей: строка живёт в узкой подписи под постером, и без
 * них «1 ч» рвалось по границе строки.
 */
fun formatWatchLeft(ms: Long): String {
    val totalMinutes = (ms / 60_000).coerceAtLeast(1)
    val hours = totalMinutes / 60
    val minutes = totalMinutes % 60
    return when {
        hours > 0 && minutes > 0 -> "$hours ч $minutes мин"
        hours > 0 -> "$hours ч"
        else -> "$minutes мин"
    }
}
